/*
 * 各テーブル要素は {レジスタアドレス, 設定値} で、宣言順にセンサーへ書き込む。
 * 0xFF はバンク選択レジスタ (0x00: DSP、0x01: Sensor)。{0xFF, 0xFF} は配列終端。
 * レジスタアドレスの意味は選択中のバンクで異なる。
 *
 * Sensor バンクの主なレジスタ:
 *   0x03 VREF: 垂直読み出し位置の下位ビット
 *   0x04 COM1, 0x09 COM2: センサー共通動作と露出関連制御
 *   0x11 CLKRC: センサー内部クロック分周
 *   0x12 COM7: センサー動作モード
 *   0x13 COM8: AEC/AGC/AWB (自動露出/ゲイン/白バランス)
 *   0x14 COM9: 自動ゲイン上限
 *   0x17 HSTART / 0x18 HSTOP: 水平読み出し範囲
 *   0x19 VSTART / 0x1A VSTOP: 垂直読み出し範囲
 *   0x24 AEW / 0x25 AEB / 0x26 VPT: 自動露出の輝度しきい値
 *   0x32 HREF: 水平読み出し位置の下位ビット
 *
 * DSP バンクの主なレジスタ:
 *   0x50 CTRLI: クロップ/スケーリング制御
 *   0x51 HSIZE / 0x52 VSIZE: DSP処理領域の幅/高さ
 *   0x53 XOFFL / 0x54 YOFFL / 0x55 VHYX: オフセットと寸法の上位ビット
 *   0x5A ZMOW / 0x5B ZMOH / 0x5C ZMHH: 縮小後の出力寸法
 *   0xD3 R_DVP_SP: DVP出力クロック分周
 *   0xDA IMAGE_MODE: 画像出力形式
 *   0xE0 RESET: DSP処理ブロック制御
 *
 * 0x7C/0x7D、0x91/0x93/0x97 などの連続書込みは内部係数列。
 * 各値は組み合わせで画質を調整するため、書込み順を変えないこと。
 */

